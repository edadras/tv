import 'dart:convert';
import 'dart:typed_data';

/// Subtitle files in the wild are rarely UTF-8. Persian/Arabic ones are
/// usually Windows-1256 and Western ones Windows-1252, so we sniff the bytes
/// instead of trusting anything. No native dependency, works on every target.
class TextCodec {
  const TextCodec._();

  /// Decodes [bytes] to a Dart string, guessing the encoding.
  /// The BOM is stripped and CRLF normalised to LF.
  static String decode(Uint8List bytes) {
    final text = _decodeRaw(bytes);
    return text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  }

  static String _decodeRaw(Uint8List b) {
    if (b.length >= 3 && b[0] == 0xEF && b[1] == 0xBB && b[2] == 0xBF) {
      return utf8.decode(b.sublist(3), allowMalformed: true);
    }
    if (b.length >= 2 && b[0] == 0xFF && b[1] == 0xFE) return _utf16(b, 2, little: true);
    if (b.length >= 2 && b[0] == 0xFE && b[1] == 0xFF) return _utf16(b, 2, little: false);

    // Valid UTF-8 is overwhelmingly likely to be intended as UTF-8.
    try {
      return const Utf8Decoder(allowMalformed: false).convert(b);
    } on FormatException {
      // Not UTF-8: fall through to the single byte code pages.
    }

    if (!_looksArabic(b)) return _singleByte(b, _cp1252);
    return _persianize(_singleByte(b, _cp1256));
  }

  /// Windows-1256 has no Persian yeh or kaf, so Persian subtitles saved in it
  /// come back spelled with the Arabic letters and render with the wrong
  /// shapes. We only rewrite them when the text proves it is Persian by
  /// containing a letter Arabic does not use — an Arabic subtitle is left
  /// exactly as it was decoded.
  static String _persianize(String s) {
    const persianOnly = ['پ', 'چ', 'ژ', 'گ']; // پ چ ژ گ
    if (!persianOnly.any(s.contains)) return s;
    return s
        .replaceAll('ي', 'ی') // ي -> ی
        .replaceAll('ك', 'ک'); // ك -> ک
  }

  static String _utf16(Uint8List b, int start, {required bool little}) {
    final units = <int>[];
    for (var i = start; i + 1 < b.length; i += 2) {
      units.add(little ? b[i] | (b[i + 1] << 8) : (b[i] << 8) | b[i + 1]);
    }
    return String.fromCharCodes(units);
  }

  /// True when the high bytes cluster in the Windows-1256 Arabic letter block.
  static bool _looksArabic(Uint8List b) {
    var high = 0, arabic = 0;
    final limit = b.length < 8192 ? b.length : 8192;
    for (var i = 0; i < limit; i++) {
      final c = b[i];
      if (c < 0x80) continue;
      high++;
      // 0xC1..0xFE is the Arabic letter range, with a few Latin strays.
      if (c >= 0xC1 && c <= 0xFE) arabic++;
      // Persian-only letters (peh/tcheh/jeh/gaf/keheh) CP1252 never produces.
      if (c == 0x81 || c == 0x8D || c == 0x8E || c == 0x90 || c == 0x98) arabic += 4;
    }
    return high > 0 && arabic / high > .6;
  }

  static String _singleByte(Uint8List b, List<int> table) {
    final out = StringBuffer();
    for (final c in b) {
      out.writeCharCode(c < 0x80 ? c : table[c - 0x80]);
    }
    return out.toString();
  }

